#!/usr/bin/env node
/**
 * Document Diagnostics — Rule COPY MAP generator.
 *
 * Deterministically renders `docs/diagnostics/DOCUMENT-DIAGNOSTICS-RULE-COPY-MAP.md`
 * from the THREE authorities (no hand-maintained drift):
 *   1. `DOCUMENT_DIAGNOSTIC_RULE_REGISTRY`      — rule id / severity / location /
 *                                                 interaction / locatable;
 *   2. `DOCUMENT_DIAGNOSTIC_COPY_TABLE` + `resolveDiagnosticCopy`
 *                                               — the canonical 标题 / 说明 / 修复建议;
 *   3. `INLINE_HINT_BY_CODE_V514R5`             — the existing short in-body label.
 *
 * The TS authorities are bundled in-memory with the already-present esbuild
 * devDependency (same pattern as generate-capability-matrix.mjs). Running it
 * twice is byte-identical (no timestamps / randomness).
 */
import { build } from 'esbuild'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { createHash } from 'node:crypto'
import { mkdirSync, rmSync, writeFileSync, existsSync, readFileSync } from 'node:fs'
import os from 'node:os'
import path from 'node:path'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(here, '..', '..')
const srcDir = path.join(root, 'src', 'document-utilities')
const outDir = path.join(root, 'docs', 'diagnostics')
const outFile = path.join(outDir, 'DOCUMENT-DIAGNOSTICS-RULE-COPY-MAP.md')

const result = await build({
  stdin: {
    contents: [
      "export { DOCUMENT_DIAGNOSTIC_RULE_REGISTRY, resolvePresentationSeverity, resolvedRuntimeCodesOf } from './document-diagnostic-location'",
      "export { DOCUMENT_DIAGNOSTIC_COPY_TABLE, DOCUMENT_DIAGNOSTIC_RULE_PRIORITY, resolveRulePriority } from './document-diagnostic-copy-v1'",
      "export { INLINE_HINT_BY_CODE_V514R5 } from './document-diagnostic-inline-presentation-v514-r5'",
    ].join('\n'),
    resolveDir: srcDir,
    sourcefile: 'rule-copy-map-generator-entry.ts',
    loader: 'ts',
  },
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node18',
  write: false,
  logLevel: 'silent',
})

if (!result.outputFiles || result.outputFiles.length === 0) {
  throw new Error('esbuild produced no output for the rule copy map entry')
}

const tmpFile = path.join(os.tmpdir(), `inkchapter-rule-copy-map-${process.pid}.mjs`)
writeFileSync(tmpFile, result.outputFiles[0].text, 'utf8')

/**
 * Curated wording normalization records (现状 → 建议). These document the REAL
 * producer strings that the copy authority normalizes and CANNOT be derived
 * from the code (they are the "before" snapshot).
 */
const WORDING_NORMALIZATION = [
  ['严重程度前缀', '消息内嵌 `警告：…` / `⚠ 严格模式结构错误：…`，与其它规则不一致', '标题/说明不含严重程度前缀；严重程度只由颜色/图标表达', ['DOCUMENT_TERMINAL_NEWLINE_MISSING', 'DOCUMENT_TRAILING_BLANK_LINES_EXCESSIVE', 'STRICT_FIRST_H1_POSITION']],
  ['术语统一', '同一概念出现多种叫法（图名 / 图片名称、表名 / 表格名称、代码名 / 代码块名称）', '统一为「图片/图名、表格/表名、代码块/代码块名称」', ['FIGURE_MISSING_NAME', 'FIGURE_DUPLICATE_NAME', 'TABLE_MISSING_NAME', 'CODE_MISSING_NAME', 'CODE_DUPLICATE_NAME']],
  ['编号提示统一', '「编号重复：N」「编号顺序异常：N」说法零散', '统一为「<对象>编号重复/顺序异常」+ 一致说明与修复建议', ['FIGURE_NUMBER_DUPLICATE', 'TABLE_NUMBER_DUPLICATE', 'CODE_NUMBER_DUPLICATE', 'FIGURE_NUMBER_ORDER_INVALID', 'TABLE_NUMBER_ORDER_INVALID', 'CODE_NUMBER_ORDER_INVALID', 'FORMULA_NUMBER_ORDER_INVALID']],
  ['重复警告统一', '「重复的图名「X」」「重复的表名「X」」「重复的标题文字「X」」句式不一', '统一为「<对象>名称重复」/「标题文字重复」，并统一建议「…以互相区分」', ['FIGURE_DUPLICATE_NAME', 'TABLE_DUPLICATE_NAME', 'CODE_DUPLICATE_NAME', 'HEADING_DUPLICATE_TEXT']],
  ['标题句式统一', '「存在空标题」「标题存在重复的规范身份」等主语/句式不一致', '统一为陈述式名词短语（如「标题为空」「标题规范身份重复」）', ['HEADING_EMPTY_TEXT', 'HEADING_DUPLICATE_IDENTITY']],
  ['文档完整性统一', '「文档仅包含标题」与「文档只有标题结构」用词不一', '统一为「文档仅包含标题 / 文档仅包含标题结构」', ['DOCUMENT_HEADING_ONLY_NO_BODY', 'DOCUMENT_HEADINGS_ONLY_NO_BODY']],
  ['中英文/格式统一', '`Front Matter`、`$$`、`H1` 等中英混排前后空格与标点不统一', '统一中英文间空格、统一使用中文顿号与「」引号、统一句末标点', ['FRONTMATTER_UNCLOSED', 'FORMULA_BLOCK_UNCLOSED', 'HEADING_LEVEL_GAP', 'LATENT_ATX_HEADING_MARKER']],
]

let markdown
let summary
try {
  const mod = await import(pathToFileURL(tmpFile).href)
  const registry = mod.DOCUMENT_DIAGNOSTIC_RULE_REGISTRY
  const copyTable = mod.DOCUMENT_DIAGNOSTIC_COPY_TABLE
  const inlineHints = mod.INLINE_HINT_BY_CODE_V514R5
  const resolvePresentationSeverity = mod.resolvePresentationSeverity
  const resolvedRuntimeCodesOf = mod.resolvedRuntimeCodesOf
  const resolveRulePriority = mod.resolveRulePriority

  const families = Object.values(registry).slice().sort((a, b) => (a.familyId < b.familyId ? -1 : a.familyId > b.familyId ? 1 : 0))

  const sevLabel = (s) => (s === 'error' ? '错误' : s === 'warning' ? '警告' : '提示')
  const locatableOf = (meta) => (meta.implementationStatus === 'IMPLEMENTED' ? '是' : '否（未实现）')

  const lines = []
  lines.push('# Document Diagnostics — Rule Copy Map')
  lines.push('')
  lines.push('> AUTO-GENERATED by `scripts/document-diagnostics/generate-rule-copy-map.mjs`.')
  lines.push('> Do NOT edit by hand — every structural fact derives from')
  lines.push('> `DOCUMENT_DIAGNOSTIC_RULE_REGISTRY` + `DOCUMENT_DIAGNOSTIC_COPY_TABLE`')
  lines.push('> + `INLINE_HINT_BY_CODE_V514R5`.')
  lines.push('')
  lines.push('## Summary')
  lines.push('')
  const errFamilies = families.filter((m) => m.presentationSeverity === 'error').length
  const warnFamilies = families.filter((m) => m.presentationSeverity === 'warning').length
  const hintFamilies = families.filter((m) => m.presentationSeverity === 'hint').length
  const codeCount = families.reduce((n, m) => n + resolvedRuntimeCodesOf(m).length, 0)
  lines.push('```text')
  lines.push(`REGISTERED_RULE_FAMILY_COUNT=${families.length}`)
  lines.push(`RESOLVED_RUNTIME_CODE_COUNT=${codeCount}`)
  lines.push(`ERROR_FAMILY_COUNT=${errFamilies}`)
  lines.push(`WARNING_FAMILY_COUNT=${warnFamilies}`)
  lines.push(`HINT_FAMILY_COUNT=${hintFamilies}`)
  lines.push('```')
  lines.push('')
  lines.push('## Rule map')
  lines.push('')
  lines.push('| RuleId (家族) | 运行码 | 严重程度 | 可否定位 | 位置策略 | 交互 | 现状内联短标 | 建议标题 | 建议说明 | 建议修复建议 |')
  lines.push('| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |')
  for (const meta of families) {
    const codes = resolvedRuntimeCodesOf(meta).join('<br>')
    const sev = sevLabel(resolvePresentationSeverity(meta.internalSeverity))
    const locatable = locatableOf(meta)
    const inline = inlineHints[meta.familyId] ?? inlineHints[meta.ruleId] ?? '（无映射/动态）'
    const spec = copyTable[meta.familyId] ?? copyTable[meta.ruleId] ?? null
    const suggestedTitle = spec && spec.title ? spec.title : '（动态：沿用规则事实标题）'
    const desc = spec ? spec.description : '（其余由运行期事实说明）'
    const fix = spec ? spec.suggestion : '（未登记）'
    const clean = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ')
    lines.push(`| \`${meta.familyId}\` | ${codes} | ${sev} | ${locatable} | ${meta.locationStrategy} | ${meta.interactionMode} | ${clean(inline)} | ${clean(suggestedTitle)} | ${clean(desc)} | ${clean(fix)} |`)
  }
  lines.push('')
  lines.push('## 文案规范化记录（现状 → 建议）')
  lines.push('')
  for (const [kind, before, after, codes] of WORDING_NORMALIZATION) {
    lines.push(`### ${kind}`)
    lines.push('')
    lines.push(`- 现状：${before}`)
    lines.push(`- 建议：${after}`)
    lines.push(`- 涉及规则：${codes.map((c) => `\`${c}\``).join('、')}`)
    lines.push('')
  }
  lines.push('## 排序与视图')
  lines.push('')
  lines.push('- 默认排序：Markdown 源码位置（band → 行 → 列），文末问题（document-end）始终最后。')
  lines.push('- 同位置并列：严重程度（错误 → 警告 → 提示）→ 稳定规则优先级（`DOCUMENT_DIAGNOSTIC_RULE_PRIORITY`）。')
  lines.push('- 可切换排序：按位置 / 按严重程度 / 按问题类型；可按问题类型筛选；可选按问题类型分组。')
  lines.push('- 筛选只删除条目、绝不重排幸存项；分组只是叠加展示、不改变组内顺序。')
  lines.push('')
  markdown = lines.join('\n')

  summary = { families: families.length, codeCount, errFamilies, warnFamilies, hintFamilies }
} finally {
  rmSync(tmpFile, { force: true })
}

const hashFirst = createHash('sha256').update(markdown).digest('hex')
mkdirSync(outDir, { recursive: true })
const previous = existsSync(outFile) ? readFileSync(outFile, 'utf8') : null
writeFileSync(outFile, markdown, 'utf8')
process.stdout.write(`Wrote ${path.relative(root, outFile).replace(/\\/g, '/')}\n`)
process.stdout.write(`families=${summary.families} codes=${summary.codeCount} error=${summary.errFamilies} warning=${summary.warnFamilies} hint=${summary.hintFamilies}\n`)
process.stdout.write(`sha256=${hashFirst} previousChanged=${previous !== markdown}\n`)
